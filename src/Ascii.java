public class Ascii {
    // Attributes
    private char symbol;

    // Constructor
    Ascii(char symbol) {
        this.setSymbol(symbol);
    }

    // Getters
    public char getSymbol() {
        return this.symbol;
    }

    // Setters
    public void setSymbol(char symbol) {
        this.symbol = symbol;
    }


}
